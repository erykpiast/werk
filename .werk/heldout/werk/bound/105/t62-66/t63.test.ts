/** Held-out steps of ticket 63: held links, accept of a branch, discard, and counts. */
import { expect, test } from 'bun:test'
import { events, project } from './helpers.ts'

const lineOf = (text: string, needle: string) => text.split('\n').filter((l) => l.includes(needle))

test('63.1 A link to a ghost is held, and it goes live on accept with no extra link event', () => {
  const p = project()
  p.real('storage', 'Storage')
  p.ok('add', 'use-sqlite', '--title', 'Use SQLite', '--parent', 'storage')
  p.ok('link', 'use-sqlite', 'storage', '--type', 'depends_on', '--why', 'the basis')
  const held = lineOf(p.show('use-sqlite'), 'depends_on -> #storage')
  expect(held).toHaveLength(1)
  expect(held[0]).toContain('(held)')
  const live = lineOf(p.show('storage'), 'depends_on <- #use-sqlite').filter((l) => !l.includes('(held)'))
  expect(live).toHaveLength(0)
  p.ok('accept', 'use-sqlite', '--actor', 'you')
  const after = lineOf(p.show('use-sqlite'), 'depends_on -> #storage')
  expect(after).toHaveLength(1)
  expect(after[0]).not.toContain('(held)')
  const links = events(p).filter(
    (e) => e.type === 'edge.linked' && e.payload.from === 'use-sqlite' && e.payload.to === 'storage' && e.payload.type === 'depends_on',
  )
  expect(links).toHaveLength(1)
})

test('63.2 Accepting a ghost child also accepts its ghost parent, but not a ghost it depends on', () => {
  const p = project()
  p.real('platform', 'Platform')
  p.ok('add', 'auth', '--title', 'Auth', '--parent', 'platform')
  p.ok('add', 'magic-links', '--title', 'Magic links', '--parent', 'auth')
  p.ok('add', 'email-service', '--title', 'Email service', '--parent', 'platform')
  p.ok('link', 'magic-links', 'email-service', '--type', 'depends_on')
  p.ok('accept', 'magic-links', '--actor', 'you')
  expect(p.show('magic-links')).toContain('state: real')
  const auth = p.show('auth')
  expect(auth).toContain('state: real')
  expect(auth).toContain('parent: #platform')
  expect(p.show('email-service')).toContain('state: ghost')
  const edge = lineOf(p.show('magic-links'), 'depends_on -> #email-service')
  expect(edge).toHaveLength(1)
  expect(edge[0]).toContain('(held)')
})

test('63.3 An accept takes the card\'s own ghost options and sources with it', () => {
  const p = project()
  p.decided('storage', 'Storage')
  p.ok('add', 'use-sqlite', '--title', 'Use SQLite', '--parent', 'storage')
  p.ok('add', 'use-postgres', '--kind', 'option', '--title', 'Use Postgres', '--why-not', 'Needs a server')
  p.ok('link', 'use-postgres', 'use-sqlite', '--type', 'alternative_to')
  p.ok('add', 'benchmark-notes', '--kind', 'source', '--title', 'Benchmark notes')
  p.ok('link', 'use-sqlite', 'benchmark-notes', '--type', 'supported_by')
  // The contract needs a kill criterion to decide; the agent records one as setup.
  p.ok('kill', 'use-sqlite', '--form', 'revisit')
  const who = p.w('edit', 'use-sqlite', '--who', 'you')
  const status = p.w('status', 'use-sqlite', 'decided')
  expect(who.code).toBe(0)
  expect(status.code).toBe(0)
  p.ok('accept', 'use-sqlite', '--actor', 'you')
  const card = p.show('use-sqlite')
  expect(card).toContain('state: real')
  expect(card).toContain('status: decided')
  expect(card).toContain('who: you')
  const opt = p.show('use-postgres')
  expect(opt).toContain('state: real')
  expect(opt).toContain('kind: option')
  expect(opt).toContain('why-not: Needs a server')
  const src = p.show('benchmark-notes')
  expect(src).toContain('state: real')
  const edge = lineOf(src, 'supported_by <- #use-sqlite')
  expect(edge).toHaveLength(1)
  expect(edge[0]).not.toContain('(held)')
})

test('63.4 Discarding a ghost parent discards its whole ghost branch', () => {
  const p = project()
  p.real('platform', 'Platform')
  p.ok('add', 'auth', '--title', 'Auth', '--parent', 'platform')
  p.ok('add', 'magic-links', '--title', 'Magic links', '--parent', 'auth')
  p.ok('add', 'passwords', '--kind', 'option', '--title', 'Passwords', '--why-not', 'Weak')
  p.ok('link', 'passwords', 'magic-links', '--type', 'alternative_to')
  p.ok('discard', 'auth')
  for (const id of ['auth', 'magic-links', 'passwords']) expect(p.w('show', id).code).not.toBe(0)
  const platform = p.show('platform')
  expect(platform).toContain('state: real')
  expect(platform).not.toContain('refines <-')
  expect(platform).not.toContain('#auth')
})

test('63.5 A ghost changes no count of a real card until it is accepted', () => {
  const p = project()
  p.decided('storage', 'Storage')
  p.decided('cache', 'Cache', { parent: 'storage' })
  const rollup = (text: string) => lineOf(text, 'rollup:')[0]
  const before = rollup(p.show('storage'))
  expect(before).toBeDefined()
  expect(p.stale()).not.toContain('#storage')
  p.ok('add', 'use-sqlite', '--title', 'Use SQLite', '--parent', 'storage', '--who', 'you')
  p.ok('add', 'use-pg', '--kind', 'option', '--title', 'Use Postgres', '--why-not', 'Server')
  p.ok('link', 'use-pg', 'use-sqlite', '--type', 'alternative_to')
  p.ok('kill', 'use-sqlite', '--form', 'revisit')
  p.ok('status', 'use-sqlite', 'decided')
  expect(rollup(p.show('storage'))).toBe(before)
  expect(p.stale()).not.toContain('#storage')
  p.ok('accept', 'use-sqlite', '--actor', 'you')
  const after = rollup(p.show('storage'))
  expect(before).toContain('2 cards')
  expect(after).toContain('3 cards')
  expect(after).toContain('3 decided')
})
