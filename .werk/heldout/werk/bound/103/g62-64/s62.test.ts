import { expect, setDefaultTimeout, test } from 'bun:test'
setDefaultTimeout(60_000)
import { project } from './helpers.ts'

test('62.1 an agent proposes a card and a person accepts it into the map', () => {
  const c = project()
  c.ok(['add', 'base', '--title', 'Base card'])
  c.ok(['accept', 'base', '--actor', 'you'])
  expect(c.log().length).toBeGreaterThan(0)
  const add = c.appendsOne(['add', 'log-card', '--title', 'Use a log', '--body', 'Every change is an event.', '--why', 'Nothing is lost.'])
  expect(add.stdout).toContain('proposed')
  const ghost = c.show('log-card')
  expect(ghost).toContain('Use a log')
  expect(ghost).toContain('Every change is an event.')
  expect(ghost).toContain('Nothing is lost.')
  expect(ghost).toMatch(/ghost/)
  c.appendsOne(['accept', 'log-card', '--actor', 'you'])
  const real = c.show('log-card')
  expect(real).toContain('Use a log')
  expect(real).toContain('Every change is an event.')
  expect(real).toContain('Nothing is lost.')
  expect(real).toContain('state: real')
  expect(real).not.toMatch(/ghost/)
})

test('62.2 an accept without the person claim refuses and leaves the ghost waiting', () => {
  const c = project()
  c.ok(['add', 'g', '--title', 'A ghost'])
  c.refuses(['accept', 'g'])
  expect(c.show('g')).toMatch(/state: ghost/)
  c.ok(['accept', 'g', '--actor', 'you'])
  expect(c.show('g')).toContain('state: real')
})

test('62.3 the words of a ghost are frozen', () => {
  const c = project()
  c.ok(['add', 'g', '--title', 'Use a log'])
  c.refuses(['edit', 'g', '--body', 'A new body'])
  c.refuses(['retitle', 'g', '--title', 'Use an append-only log'])
  c.refuses(['add', 'g', '--title', 'Something else'])
  const s = c.show('g')
  expect(s).toContain('Use a log')
  expect(s).toMatch(/state: ghost/)
})

test('62.4 a retitle on a real card shows only the new title and keeps the old one in the log', () => {
  const c = project()
  c.ok(['add', 'g', '--title', 'Use a log'])
  c.ok(['accept', 'g', '--actor', 'you'])
  const before = c.log()
  c.appendsOne(['retitle', 'g', '--title', 'Use an append-only log'])
  const s = c.show('g')
  expect(s).toContain('Use an append-only log')
  expect(s).not.toContain('Use a log')
  expect(before.some((l) => l.includes('"Use a log"'))).toBe(true)
  expect(c.log().slice(0, before.length)).toEqual(before)
  c.ok(['edit', 'g', '--body', 'Events are never deleted.'])
  const s2 = c.show('g')
  expect(s2).toContain('Events are never deleted.')
  expect(s2).toContain('Use an append-only log')
})

test('62.5 an option, a source and an excerpt also enter as ghosts', () => {
  const c = project()
  c.ok(['add', 'card', '--title', 'A real card'])
  c.ok(['accept', 'card', '--actor', 'you'])
  const opt = c.appendsOne(['add', 'opt', '--kind', 'option', '--title', 'Use a table', '--why-not', 'Rows get overwritten'])
  c.ok(['link', 'opt', 'card', '--type', 'alternative_to'])
  const src = c.appendsOne(['add', 'src', '--kind', 'source', '--title', 'Design notes', '--body', 'From the kickoff'])
  const exc = c.appendsOne(['add', 'exc', '--kind', 'excerpt', '--title', 'A quote', '--body', 'We never delete'])
  for (const r of [opt, src, exc]) expect(r.stdout).toContain('proposed')
  const so = c.show('opt')
  expect(so).toContain('Use a table')
  expect(so).toContain('Rows get overwritten')
  expect(so).toMatch(/state: ghost/)
  const ss = c.show('src')
  expect(ss).toContain('Design notes')
  expect(ss).toContain('From the kickoff')
  expect(ss).toMatch(/state: ghost/)
  const se = c.show('exc')
  expect(se).toContain('A quote')
  expect(se).toContain('We never delete')
  expect(se).toMatch(/state: ghost/)
  c.ok(['accept', 'opt', '--actor', 'you'])
  const so2 = c.show('opt')
  expect(so2).toContain('state: real')
  expect(so2).toContain('why-not: Rows get overwritten')
  expect(c.show('src')).toMatch(/state: ghost/)
  expect(c.show('exc')).toMatch(/state: ghost/)
})
