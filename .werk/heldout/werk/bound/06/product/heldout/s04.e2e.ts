import { expect, test, type Page } from '@playwright/test'
import { setup } from './common.ts'

const sub = (page: Page) => page.getByRole('region', { name: 'sub-cards' })
const row = (page: Page, title: string) => sub(page).getByRole('listitem').filter({ has: page.getByRole('link', { name: title, exact: true }) })
const detail = (page: Page) => page.getByRole('region', { name: 'card detail' })

test('04.1 a new card waits as a ghost until the person accepts it with a ✓', async ({ page }) => {
  const { p, s } = await setup((p) => {
    p.decided('checkout', 'Checkout flow')
    p.real('pay', 'Payment step', '--parent', 'checkout', '--who', 'me')
    p.ok('link', 'pay', 'checkout', '--type', 'depends_on')
    p.ok('kill', 'pay', 'never')
    p.ok('decide', 'pay')
    p.ok('reopen', 'checkout', '--reason', 'rejected', '--why', 'to get a staleness mark')
    p.ok('add', 'other-ghost', '--title', 'Another proposal', '--parent', 'checkout')
  })
  await page.goto(`${s.url}/#checkout`)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Checkout flow')
  const rootBefore = await (await fetch(`${s.url}/api/map`)).json()
  const staleBefore = p.werk('stale').stdout
  await page.goto(`${s.url}/`)
  const rootTextBefore = await page.getByRole('main').innerText()
  await expect.soft(page.getByText(/rollup/i).first(), 'the map shows a rollup').toBeVisible({ timeout: 1000 })
  await expect.soft(page.getByText(/unchallenged/i).first(), 'the map shows an unchallenged count').toBeVisible({ timeout: 1000 })
  await page.goto(`${s.url}/#checkout`)
  const before = p.events().length
  const add = p.werk('add', 'retry', '--title', 'Retry payment', '--parent', 'checkout')
  expect(add.code, add.out).toBe(0)
  expect(add.stdout).toContain('proposed')
  expect(add.stdout).not.toContain('added')
  const evs = p.events()
  expect(evs.length).toBe(before + 1)
  expect(evs.at(-1)).toMatchObject({ type: 'proposed', id: 'retry' })
  const ghost = row(page, 'Retry payment')
  await expect(ghost).toHaveClass(/ghost/)
  await expect(ghost).toHaveCSS('border-top-style', 'dashed')
  const bg = await ghost.evaluate((el) => getComputedStyle(el).backgroundColor)
  expect(bg === 'rgba(0, 0, 0, 0)' || bg === 'transparent', `background ${bg}`).toBe(true)
  const color = await ghost.evaluate((el) => getComputedStyle(el).color)
  const [r, g, b] = color.match(/\d+/g)!.map(Number)
  expect(Math.max(r!, g!, b!) - Math.min(r!, g!, b!), `ghost text colour ${color} is grey`).toBeLessThan(20)
  // Marks and counts are the same as before the add.
  expect(p.werk('stale').stdout).toBe(staleBefore)
  const mapAfter = await (await fetch(`${s.url}/api/map`)).json()
  for (const id of Object.keys(rootBefore.cards)) {
    expect(mapAfter.cards[id].stale).toEqual(rootBefore.cards[id].stale)
    expect(mapAfter.cards[id].paused).toEqual(rootBefore.cards[id].paused)
  }
  expect(mapAfter.links).toEqual(rootBefore.links)
  await page.goto(`${s.url}/`)
  expect(await page.getByRole('main').innerText()).toBe(rootTextBefore)
  await page.goto(`${s.url}/#checkout`)
  const n = p.events().length
  await row(page, 'Retry payment').getByRole('button', { name: 'accept #retry' }).click()
  await expect(row(page, 'Retry payment')).not.toHaveClass(/ghost/)
  const after = p.events()
  expect(after.length).toBe(n + 1)
  expect(after.at(-1)).toMatchObject({ type: 'accepted', id: 'retry' })
  await expect(row(page, 'Another proposal')).toHaveClass(/ghost/)
  const map = await (await fetch(`${s.url}/api/map`)).json()
  expect(map.cards['other-ghost'].proposed).toBe(true)
  expect(map.cards.retry.proposed).toBeUndefined()
})

test('04.2 accepting a ghost child accepts its ghost parent, and its held edge goes live', async ({ page }) => {
  const { p, s } = await setup((p) => {
    p.real('payments', 'Payments')
    p.real('fraud', 'Fraud rules')
  })
  p.ok('add', 'refunds', '--title', 'Refunds', '--parent', 'payments')
  p.ok('add', 'partial', '--title', 'Partial refunds', '--parent', 'refunds')
  p.ok('link', 'partial', 'fraud', '--type', 'depends_on', '--why', 'a refund passes the fraud rules')
  p.ok('add', 'partial:opt0', '--kind', 'option', '--title', 'Full refunds only', '--why-not', 'customers ask for part', '--alternative-to', 'partial')
  p.ok('add', 'src-psp', '--kind', 'source', '--title', 'The PSP refund API docs')
  p.ok('link', 'partial', 'src-psp', '--type', 'supported_by')
  await page.goto(`${s.url}/#partial`)
  await expect(detail(page)).toHaveClass(/ghost/)
  const dep = detail(page).getByRole('region', { name: 'depends on' })
  await expect(dep.getByRole('link', { name: 'Fraud rules' })).toBeVisible()
  let map = await (await fetch(`${s.url}/api/map`)).json()
  expect(map.ghostEdges).toContainEqual(expect.objectContaining({ from: 'partial', to: 'fraud', type: 'depends_on' }))
  expect(map.links.some((l: any) => l.from === 'partial')).toBe(false)
  const n = p.events().length
  await detail(page).getByRole('button', { name: 'accept #partial', exact: true }).click()
  await expect(detail(page)).not.toHaveClass(/ghost/)
  const evs = p.events()
  expect(evs.length).toBe(n + 1)
  expect(evs.at(-1)).toMatchObject({ type: 'accepted', id: 'partial' })
  map = await (await fetch(`${s.url}/api/map`)).json()
  for (const id of ['refunds', 'partial', 'partial:opt0', 'src-psp']) expect(map.cards[id].proposed, id).toBeUndefined()
  expect(map.links).toContainEqual(expect.objectContaining({ from: 'partial', to: 'fraud', type: 'depends_on' }))
  await expect(detail(page).getByRole('region', { name: 'options' }).getByRole('listitem')).not.toHaveClass(/ghost/)
  await expect(detail(page).getByRole('region', { name: 'evidence' }).getByRole('listitem')).not.toHaveClass(/ghost/)
  await expect(detail(page).getByRole('region', { name: 'depends on' }).getByRole('link', { name: 'Fraud rules' })).toBeVisible()
  await page.goto(`${s.url}/#refunds`)
  await expect(detail(page)).not.toHaveClass(/ghost/)
  await expect(detail(page).getByText('proposed')).toHaveCount(0)
})

test('04.3 discarding a ghost parent drops its ghost children', async ({ page }) => {
  const { p, s } = await setup((p) => p.real('onboarding', 'Onboarding'))
  await page.goto(`${s.url}/`)
  const rootBefore = await page.getByRole('main').innerText()
  await page.goto(`${s.url}/#onboarding`)
  const cardBefore = await page.getByRole('main').innerText()
  const staleBefore = p.werk('stale').stdout
  p.ok('add', 'email', '--title', 'Email verification', '--parent', 'onboarding')
  p.ok('add', 'resend', '--title', 'Resend email', '--parent', 'email')
  await expect(row(page, 'Email verification')).toHaveClass(/ghost/)
  const r = p.werk('discard', 'email')
  expect(r.code, r.out).toBe(0)
  await expect(page.getByText('Email verification')).toHaveCount(0)
  await expect(page.getByText('Resend email')).toHaveCount(0)
  await expect(page.locator('.ghost')).toHaveCount(0)
  expect(await page.getByRole('main').innerText()).toBe(cardBefore)
  await page.goto(`${s.url}/`)
  expect(await page.getByRole('main').innerText()).toBe(rootBefore)
  expect(p.werk('stale').stdout).toBe(staleBefore)
})

test('04.4 the words of a ghost are frozen, but it can be proposed already decided', async ({ page }) => {
  const { p, s } = await setup((p) => {
    p.real('search', 'Search')
    p.decided('engine', 'Indexing engine')
  })
  p.ok('add', 'search-index', '--title', 'Search index', '--why', 'first why', '--body', 'first body', '--parent', 'search')
  const again = p.werk('add', 'search-index', '--title', 'Another title', '--body', 'other body')
  expect(again.code).not.toBe(0)
  expect(p.show('search-index').card).toMatchObject({ title: 'Search index', body: 'first body', why: 'first why' })
  await page.goto(`${s.url}/#search-index`)
  const text = await detail(page).innerText()
  for (const args of [['edit', 'search-index', '--body', 'b2'], ['edit', 'search-index', '--why', 'w2'], ['retitle', 'search-index', 'T2']]) {
    const r = p.werk(...args)
    expect(r.code, args.join(' ')).not.toBe(0)
  }
  expect(await detail(page).innerText()).toBe(text)
  expect(p.werk('edit', 'search-index', '--who', 'you').code).toBe(0)
  const n = p.log()
  const d1 = p.werk('status', 'search-index', 'decided')
  expect(d1.code).not.toBe(0)
  expect(d1.out).toMatch(/basis/)
  expect(d1.out).toMatch(/^\s*werk .+/m)
  expect(p.log()).toBe(n)
  expect(p.show('search-index').card).toMatchObject({ status: 'open', proposed: true })
  p.ok('link', 'search-index', 'engine', '--type', 'depends_on', '--why', 'the index is built by the engine')
  p.ok('add', 'search-index:opt0', '--kind', 'option', '--title', 'Scan every card', '--why-not', 'too slow', '--alternative-to', 'search-index')
  p.ok('kill', 'search-index', 'search takes more than a second')
  const d2 = p.werk('status', 'search-index', 'decided')
  expect(d2.code, d2.out).toBe(0)
  await expect(detail(page)).toHaveClass(/ghost/)
  await expect(detail(page).locator('.meta .status').first()).toHaveText('decided')
  const before = p.events().length
  await detail(page).getByRole('button', { name: 'accept #search-index', exact: true }).click()
  await expect(detail(page)).not.toHaveClass(/ghost/)
  expect(p.events().length).toBe(before + 1)
  const map = await (await fetch(`${s.url}/api/map`)).json()
  expect(map.cards['search-index']).toMatchObject({ status: 'decided' })
  expect(map.cards['search-index'].proposed).toBeUndefined()
  expect(map.cards['search-index:opt0'].proposed).toBeUndefined()
  expect(map.links).toContainEqual(expect.objectContaining({ from: 'search-index', to: 'engine', type: 'depends_on' }))
  expect(map.links).toContainEqual(expect.objectContaining({ from: 'search-index:opt0', to: 'search-index', type: 'alternative_to' }))
})

test('04.5 an accept from the command line needs the statement that the person asked for it', async ({ page }) => {
  const { p, s } = await setup((p) => p.real('compliance', 'Compliance'))
  p.ok('add', 'audit', '--title', 'Audit log', '--parent', 'compliance')
  await page.goto(`${s.url}/#compliance`)
  await expect(row(page, 'Audit log')).toHaveClass(/ghost/)
  const before = p.log()
  const r = p.werk('accept', 'audit')
  expect(r.code).not.toBe(0)
  expect(p.log()).toBe(before)
  await expect(row(page, 'Audit log')).toHaveClass(/ghost/)
  const ok = p.werk('accept', 'audit', '--actor', 'you')
  expect(ok.code, ok.out).toBe(0)
  await expect(row(page, 'Audit log')).not.toHaveClass(/ghost/)
})
