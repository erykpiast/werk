import { afterEach, expect, test } from 'bun:test'
import { decide, graph, project, realCard, rollupOf, type P } from './helpers.ts'

let p: P
afterEach(() => p?.cleanup())

test('63.1 a link to a ghost is held, and goes live on accept', () => {
  p = project()
  realCard(p, 'storage', 'Storage')
  p.ok(['add', 'sqlite', '--title', 'Use SQLite', '--parent', 'storage'])
  p.ok(['link', 'sqlite', 'storage', '--type', 'depends_on', '--why', 'basis'])
  expect(p.show('sqlite')).toContain('link: depends_on -> #storage (held)')
  const live = graph(p).edges.filter((e) => e.from === 'storage' || e.to === 'storage')
  expect(live.some((e) => e.type === 'depends_on' && e.from === 'sqlite')).toBe(false)
  p.ok(['accept', 'sqlite', '--actor', 'you'])
  const s = p.show('sqlite')
  expect(s).toContain('link: depends_on -> #storage')
  expect(s).not.toContain('(held)')
  const links = p.events().filter((e) => e.type === 'edge.linked' && e.payload.from === 'sqlite' && e.payload.to === 'storage' && e.payload.type === 'depends_on')
  expect(links.length).toBe(1)
})

test('63.2 accepting a ghost child accepts its ghost parent, not a ghost dependency', () => {
  p = project()
  realCard(p, 'platform', 'Platform')
  p.ok(['add', 'auth', '--title', 'Auth', '--parent', 'platform'])
  p.ok(['add', 'magic', '--title', 'Magic links', '--parent', 'auth'])
  p.ok(['add', 'email', '--title', 'Email service', '--parent', 'platform'])
  p.ok(['link', 'magic', 'email', '--type', 'depends_on'])
  p.ok(['accept', 'magic', '--actor', 'you'])
  expect(p.show('magic')).toContain('state: real')
  const auth = p.show('auth')
  expect(auth).toContain('state: real')
  expect(auth).toContain('parent: #platform')
  expect(p.show('email')).toContain('ghost')
  expect(p.show('magic')).toContain('link: depends_on -> #email (held)')
})

test('63.3 an accept takes the card\'s own ghost options and sources', () => {
  p = project()
  realCard(p, 'storage', 'Storage')
  decide(p, 'storage')
  p.ok(['add', 'sqlite', '--title', 'Use SQLite', '--parent', 'storage'])
  p.ok(['add', 'postgres', '--kind', 'option', '--title', 'Use Postgres', '--why-not', 'Too heavy to run'])
  p.ok(['link', 'postgres', 'sqlite', '--type', 'alternative_to'])
  p.ok(['add', 'bench', '--kind', 'source', '--title', 'Benchmark notes'])
  p.ok(['link', 'sqlite', 'bench', '--type', 'supported_by'])
  // Setup beyond the step text: the contract check needs a kill criterion before a decide.
  p.ok(['kill', 'sqlite', '--form', 'manual', '--text', 'watch the write rate'])
  const who = p.werk(['edit', 'sqlite', '--who', 'the storage lead'])
  const st = p.werk(['status', 'sqlite', 'decided'])
  p.ok(['accept', 'sqlite', '--actor', 'you'])
  const s = p.show('sqlite')
  expect(s).toContain('state: real')
  expect(s).toContain('status: decided')
  expect(s).toContain('who: the storage lead')
  const pg = p.show('postgres')
  expect(pg).toContain('state: real')
  expect(pg).toContain('kind: option')
  expect(pg).toContain('why-not: Too heavy to run')
  const b = p.show('bench')
  expect(b).toContain('state: real')
  expect(graph(p).edges.some((e) => e.from === 'sqlite' && e.to === 'bench' && e.type === 'supported_by')).toBe(true)
  expect([st.code, st.stderr]).toEqual([0, ''])
  expect([who.code, who.stderr]).toEqual([0, ''])
})

test('63.4 discarding a ghost parent discards its whole ghost branch', () => {
  p = project()
  realCard(p, 'platform', 'Platform')
  p.ok(['add', 'auth', '--title', 'Auth', '--parent', 'platform'])
  p.ok(['add', 'magic', '--title', 'Magic links', '--parent', 'auth'])
  p.ok(['add', 'passwords', '--kind', 'option', '--title', 'Passwords'])
  p.ok(['link', 'passwords', 'magic', '--type', 'alternative_to'])
  p.ok(['discard', 'auth'])
  const g = graph(p)
  for (const id of ['auth', 'magic', 'passwords']) {
    expect(g.nodes.some((n) => n.id === id)).toBe(false)
    expect(p.werk(['show', id]).code).not.toBe(0)
  }
  const pl = p.show('platform')
  expect(pl).toContain('state: real')
  expect(pl).not.toContain('held')
  expect(g.nodes.filter((n) => n.proposed).length).toBe(0)
})

test('63.5 a ghost changes no count of a real card until it is accepted', () => {
  p = project()
  realCard(p, 'storage', 'Storage')
  realCard(p, 'child', 'Child', ['--parent', 'storage'])
  decide(p, 'child')
  const before = rollupOf(p, 'storage')!
  expect(graph(p).marks.storage).toBeUndefined()
  p.ok(['add', 'sqlite', '--title', 'Use SQLite', '--parent', 'storage'])
  p.ok(['edit', 'sqlite', '--who', 'you', '--no-basis', 'root'])
  p.ok(['kill', 'sqlite', '--form', 'revisit'])
  p.ok(['add', 'sqlite:opt0', '--kind', 'option', '--title', 'Use files', '--why-not', 'no queries'])
  p.ok(['link', 'sqlite:opt0', 'sqlite', '--type', 'alternative_to'])
  p.ok(['status', 'sqlite', 'decided'])
  const during = rollupOf(p, 'storage')!
  expect(during.cards).toBe(before.cards)
  expect(during.unchallenged).toBe(before.unchallenged)
  expect(during).toEqual(before)
  expect(graph(p).marks.storage).toBeUndefined()
  p.ok(['accept', 'sqlite', '--actor', 'you'])
  const after = rollupOf(p, 'storage')!
  expect(after.cards).toBe(before.cards + 1)
  expect(after.decided).toBe(before.decided + 1)
})
