import { afterEach, test } from 'bun:test'
import { childrenOf, decide, expect, logLines, makeProject, ok, parentOf, realCard, type Project } from './helpers.ts'

let p: Project
afterEach(() => p?.cleanup())

test('66.1 an agent removes a bad branch and the log keeps its history', () => {
  p = makeProject()
  realCard(p, 'storage', 'Storage')
  realCard(p, 'cache', 'Cache', 'storage')
  realCard(p, 'index', 'Index', 'storage')
  realCard(p, 'eviction', 'Eviction', 'cache')
  const before = logLines(p)
  // The remove verb needs the person's claim: the agent runs it with --actor you.
  const r = p.werk(['remove', 'cache', '--actor', 'you'])
  expect(r.code).toBe(0)
  expect(p.werk(['show', 'cache']).stdout).toContain('state: removed')
  expect(p.werk(['show', 'eviction']).stdout).toContain('state: removed')
  const kids = childrenOf(p, 'storage')
  expect(kids).not.toContain('cache')
  expect(kids).not.toContain('eviction')
  expect(kids).toContain('index')
  expect(p.werk(['removed']).stdout).toContain('#cache')
  const after = logLines(p)
  expect(after.slice(0, before.length)).toEqual(before)
  expect(after.length).toBe(before.length + 1)
})

test('66.2 a person restores a removed card and its subtree with their links', () => {
  p = makeProject()
  realCard(p, 'storage', 'Storage')
  realCard(p, 'cache', 'Cache', 'storage')
  realCard(p, 'eviction', 'Eviction', 'cache')
  realCard(p, 'memory-budget', 'Memory budget')
  ok(p, ['link', 'cache', 'memory-budget', '--type', 'depends_on', '--why', 'fits the budget'])
  ok(p, ['remove', 'cache', '--actor', 'you'])
  expect(p.werk(['restore', 'cache']).code).toBe(0)
  const show = p.werk(['show', 'cache']).stdout
  expect(show).not.toContain('state: removed')
  expect(childrenOf(p, 'storage')).toContain('cache')
  expect(childrenOf(p, 'cache')).toContain('eviction')
  expect(show).toContain('link: depends_on -> #memory-budget')
  expect(p.werk(['removed']).stdout).not.toContain('#cache')
})

test('66.3 an agent removes a bad parent but keeps its good children', () => {
  p = makeProject()
  realCard(p, 'storage', 'Storage')
  realCard(p, 'bad-layer', 'Bad layer', 'storage')
  realCard(p, 'write-path', 'Write path', 'bad-layer')
  realCard(p, 'read-path', 'Read path', 'bad-layer')
  expect(p.werk(['remove', 'bad-layer', '--actor', 'you', '--reparent']).code).toBe(0)
  expect(p.werk(['show', 'bad-layer']).stdout).toContain('state: removed')
  expect(parentOf(p, 'write-path')).toBe('storage')
  expect(parentOf(p, 'read-path')).toBe('storage')
  expect(childrenOf(p, 'storage')).toEqual(expect.arrayContaining(['write-path', 'read-path']))
  expect(p.werk(['show', 'write-path']).stdout).not.toContain('removed')
  expect(p.werk(['show', 'read-path']).stdout).not.toContain('removed')
})

test('66.4 an agent finds the open cards it can work on in a subtree', () => {
  p = makeProject()
  realCard(p, 'held', 'A held card')
  decide(p, 'held', true)
  realCard(p, 'wrong', 'A wrong card')
  decide(p, 'wrong', true)
  realCard(p, 'storage', 'Storage')
  for (const [id, t] of [['cache', 'Cache'], ['index', 'Index'], ['backup', 'Backup'], ['quota', 'Quota']]) realCard(p, id!, t!, 'storage')
  ok(p, ['link', 'backup', 'held', '--type', 'depends_on', '--why', 'needs it'])
  ok(p, ['link', 'quota', 'wrong', '--type', 'depends_on', '--why', 'needs it'])
  realCard(p, 'outside', 'Outside')
  ok(p, ['reopen', 'held', '--reason', 'postponed', '--why', 'next quarter'])
  ok(p, ['reopen', 'wrong', '--reason', 'rejected', '--why', 'it is wrong'])
  const r = p.werk(['find', 'storage'])
  expect(r.code).toBe(0)
  expect(r.stdout).toContain('#cache')
  expect(r.stdout).toContain('#index')
  expect(r.stdout).not.toContain('#backup')
  expect(r.stdout).not.toContain('#quota')
  expect(r.stdout).not.toContain('#outside')
})

test('66.5 a removed branch drops out of find and comes back after a restore', () => {
  p = makeProject()
  realCard(p, 'storage', 'Storage')
  realCard(p, 'cache', 'Cache', 'storage')
  realCard(p, 'index', 'Index', 'storage')
  ok(p, ['remove', 'cache', '--actor', 'you'])
  let r = p.werk(['find', 'storage'])
  expect(r.stdout).toContain('#index')
  expect(r.stdout).not.toContain('#cache')
  ok(p, ['restore', 'cache'])
  r = p.werk(['find', 'storage'])
  expect(r.stdout).toContain('#index')
  expect(r.stdout).toContain('#cache')
})
