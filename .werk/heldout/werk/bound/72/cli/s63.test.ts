import { afterEach, expect, test } from 'bun:test'
import { project, type P } from './helpers.ts'

let p: P
afterEach(() => p?.cleanup())

const hasEdge = (edges: { from: string; to: string; type: string }[], from: string, to: string, type: string) =>
  edges.some((e) => e.from === from && e.to === to && e.type === type)

test('63.1', () => {
  p = project()
  p.realCard('storage', 'Storage')
  p.ok(['add', 'use-sqlite', '--title', 'Use SQLite', '--parent', 'storage'])
  p.ok(['link', 'use-sqlite', 'storage', '--type', 'depends_on'])
  expect(p.show('use-sqlite')).toContain('link: depends_on -> #storage (held)')
  expect(hasEdge(p.graph().edges, 'use-sqlite', 'storage', 'depends_on')).toBe(false)
  expect(p.show('storage')).not.toMatch(/link: depends_on <- #use-sqlite(?! \(held\))/)
  p.ok(['accept', 'use-sqlite', '--actor', 'you'])
  const s = p.show('use-sqlite')
  expect(s).toContain('link: depends_on -> #storage')
  expect(s).not.toContain('(held)')
  expect(hasEdge(p.graph().edges, 'use-sqlite', 'storage', 'depends_on')).toBe(true)
  const links = p.lines().map((l) => JSON.parse(l)).filter((e) => e.type === 'edge.linked' && e.payload.from === 'use-sqlite' && e.payload.to === 'storage' && e.payload.type === 'depends_on')
  expect(links).toHaveLength(1)
})

