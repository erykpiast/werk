test('63.3', () => {
  p = project()
  // Storage is decided, so it can be the basis of a decided child.
  p.decided('storage', { title: 'Storage' })
  p.ok(['add', 'use-sqlite', '--title', 'Use SQLite', '--parent', 'storage'])
  p.ok(['add', 'use-postgres', '--kind', 'option', '--title', 'Use Postgres', '--why-not', 'needs a server'])
  p.ok(['link', 'use-postgres', 'use-sqlite', '--type', 'alternative_to'])
  p.ok(['add', 'bench', '--kind', 'source', '--title', 'Benchmark notes'])
  p.ok(['link', 'use-sqlite', 'bench', '--type', 'supported_by'])
  p.ok(['kill', 'use-sqlite', '--form', 'revisit'])
  const who = p.werk(['edit', 'use-sqlite', '--who', 'you'])
  const status = p.werk(['status', 'use-sqlite', 'decided'])
  expect(who.code).toBe(0)
  expect(status.code).toBe(0)
  p.ok(['accept', 'use-sqlite', '--actor', 'you'])
  const s = p.show('use-sqlite')
  expect(s).toContain('state: real')
  expect(s).toContain('status: decided')
  expect(s).toContain('who: you')
  const o = p.show('use-postgres')
  expect(o).toContain('state: real')
  expect(o).toContain('why-not: needs a server')
  expect(p.show('bench')).toContain('state: real')
  expect(hasEdge(p.graph().edges, 'use-sqlite', 'bench', 'supported_by')).toBe(true)
})

test('63.4', () => {
  p = project()
  p.realCard('platform', 'Platform')
  p.ok(['add', 'auth', '--title', 'Auth', '--parent', 'platform'])
  p.ok(['add', 'magic-links', '--title', 'Magic links', '--parent', 'auth'])
  p.ok(['add', 'passwords', '--kind', 'option', '--title', 'Passwords'])
  p.ok(['link', 'passwords', 'magic-links', '--type', 'alternative_to'])
  p.ok(['discard', 'auth'])
  const ids = p.graph().nodes.map((n) => n.id)
  for (const id of ['auth', 'magic-links', 'passwords']) {
    expect(ids).not.toContain(id)
    expect(p.werk(['show', id]).code).not.toBe(0)
  }
  expect(p.show('platform')).toContain('state: real')
  const g = p.graph()
  const ghostChildren = [...g.edges, ...g.ghostEdges].filter((e) => e.type === 'refines' && e.to === 'platform')
  expect(ghostChildren).toHaveLength(0)
})

test('63.5', () => {
  p = project()
  p.decided('storage', { title: 'Storage' })
  p.ok(['add', 'child', '--title', 'Real child', '--parent', 'storage'])
  p.ok(['accept', 'child', '--actor', 'you'])
  p.ok(['edit', 'child', '--who', 'you'])
  p.ok(['kill', 'child', '--form', 'revisit'])
  p.ok(['status', 'child', 'decided', '--unchallenged'])
  const rollupLine = () => p.show('storage').split('\n').find((l) => l.startsWith('rollup:'))
  const before = rollupLine()
  expect(before).toContain('2 cards')
  expect(before).toContain('1 unchallenged')
  expect(p.graph().marks['storage']).toBeUndefined()

  p.ok(['add', 'use-sqlite', '--title', 'Use SQLite', '--parent', 'storage'])
  p.ok(['edit', 'use-sqlite', '--who', 'you'])
  p.ok(['kill', 'use-sqlite', '--form', 'revisit'])
  p.ok(['add', 'opt', '--kind', 'option', '--title', 'Use files', '--why-not', 'no queries'])
  p.ok(['link', 'opt', 'use-sqlite', '--type', 'alternative_to'])
  p.ok(['status', 'use-sqlite', 'decided'])
  expect(rollupLine()).toBe(before)
  expect(p.graph().marks['storage']).toBeUndefined()
  p.ok(['accept', 'use-sqlite', '--actor', 'you'])
  expect(rollupLine()).toContain('3 cards')
})
