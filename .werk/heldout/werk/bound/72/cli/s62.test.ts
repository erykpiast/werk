import { afterEach, expect, test } from 'bun:test'
import { project, type P } from './helpers.ts'

let p: P
afterEach(() => p?.cleanup())

test('62.1', () => {
  p = project()
  p.realCard('root', 'Root')
  p.ok(['add', 'other', '--title', 'Other'])
  expect(p.lines().length).toBeGreaterThan(0)
  const add = p.appendsOne(['add', 'c1', '--title', 'Use a log', '--body', 'The body text', '--why', 'The why text'])
  expect(add.stdout).toContain('proposed')
  const s1 = p.show('c1')
  expect(s1).toContain('Use a log')
  expect(s1).toContain('The body text')
  expect(s1).toContain('The why text')
  expect(s1).toMatch(/ghost/)
  p.appendsOne(['accept', 'c1', '--actor', 'you'])
  const s2 = p.show('c1')
  expect(s2).toContain('Use a log')
  expect(s2).toContain('The body text')
  expect(s2).toContain('The why text')
  expect(s2).toContain('state: real')
  expect(s2).not.toMatch(/ghost/)
})

test('62.2', () => {
  p = project()
  p.ok(['add', 'c1', '--title', 'Use a log'])
  p.refuses(['accept', 'c1'])
  expect(p.show('c1')).toMatch(/ghost/)
  p.ok(['accept', 'c1', '--actor', 'you'])
  expect(p.show('c1')).toContain('state: real')
})

test('62.3', () => {
  p = project()
  p.ok(['add', 'c1', '--title', 'Use a log'])
  p.refuses(['edit', 'c1', '--body', 'new body'])
  p.refuses(['retitle', 'c1', '--title', 'Use an append-only log'])
  p.refuses(['add', 'c1', '--title', 'Another title'])
  const s = p.show('c1')
  expect(s).toContain('Use a log')
  expect(s).toMatch(/ghost/)
})

test('62.4', () => {
  p = project()
  p.ok(['add', 'c1', '--title', 'Use a log'])
  p.ok(['accept', 'c1', '--actor', 'you'])
  const before = p.lines()
  p.appendsOne(['retitle', 'c1', '--title', 'Use an append-only log'])
  const s = p.show('c1')
  expect(s).toContain('Use an append-only log')
  expect(s).not.toContain('Use a log')
  const after = p.lines()
  expect(after.slice(0, before.length).some((l) => l.includes('"Use a log"'))).toBe(true)
  p.ok(['edit', 'c1', '--body', 'A fresh body'])
  const s2 = p.show('c1')
  expect(s2).toContain('A fresh body')
  expect(s2).toContain('Use an append-only log')
})

test('62.5', () => {
  p = project()
  p.realCard('card', 'A real card')
  const o = p.appendsOne(['add', 'opt', '--kind', 'option', '--title', 'Use Postgres', '--why-not', 'too heavy', '--parent', 'card'])
  const s = p.appendsOne(['add', 'src', '--kind', 'source', '--title', 'Benchmark notes', '--body', 'source body'])
  const e = p.appendsOne(['add', 'exc', '--kind', 'excerpt', '--title', 'A quoted line', '--body', 'excerpt body'])
  for (const r of [o, s, e]) expect(r.stdout).toContain('proposed')
  const so = p.show('opt')
  expect(so).toContain('Use Postgres')
  expect(so).toContain('why-not: too heavy')
  expect(so).toMatch(/ghost/)
  const ss = p.show('src')
  expect(ss).toContain('Benchmark notes')
  expect(ss).toContain('kind: source')
  expect(ss).toMatch(/ghost/)
  const se = p.show('exc')
  expect(se).toContain('A quoted line')
  expect(se).toContain('kind: excerpt')
  expect(se).toMatch(/ghost/)
  p.ok(['accept', 'opt', '--actor', 'you'])
  const so2 = p.show('opt')
  expect(so2).toContain('state: real')
  expect(so2).toContain('why-not: too heavy')
  expect(p.show('src')).toMatch(/ghost/)
  expect(p.show('exc')).toMatch(/ghost/)
})
