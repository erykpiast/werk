import { expect, test } from 'bun:test'
import { Checks, decidedRoot, logEvents, logText, mustRun, open, project, serve, showCard, shows } from './lib.ts'

const report = (c: Checks, id: string) => {
  console.log(`\n=== ${id}\n${c.report()}`)
  expect(c.misses).toEqual([])
}

test('02.1 a retitle appends one event and the map shows only the new title', () => {
  const c = new Checks()
  const p = project()
  mustRun(p, ['add', 'a', '--title', 'Use a log'])
  mustRun(p, ['add', 'b', '--title', 'Cards fold from it'])
  mustRun(p, ['link', 'b', 'a', '--type', 'refines'])
  const saved = logText(p.dir)
  const r = p.run(['retitle', 'a', 'Use an append-only log'])
  c.ok(r.code === 0, `retitle exits 0: ${r.stdout.trim()} ${r.stderr.trim()}`)
  const now = logText(p.dir)
  c.ok(now.split('\n').filter(Boolean).length === saved.split('\n').filter(Boolean).length + 1, 'the log has exactly one more event')
  c.ok(now.startsWith(saved), 'the start of the log is byte-for-byte the saved copy')
  const root = JSON.parse(p.run(['show']).stdout)
  const rootA = root.children.find((x: any) => x.id === 'a')
  c.ok(rootA?.title === 'Use an append-only log', `the map (show with no id) shows the new title for a: ${rootA?.title}`)
  const a = showCard(p, 'a')
  c.ok(a?.card.title === 'Use an append-only log', `show a prints the new title: ${a?.card.title}`)
  c.ok(rootA?.title !== 'Use a log' && a?.card.title !== 'Use a log', 'neither the map nor show prints the old title as the title of a')
  const bPage = showCard(p, 'b')
  c.ok(bPage.trail.every((t: any) => t.title !== 'Use a log'), 'the trail of b does not use the old title')
  c.ok(now.includes('"Use a log"'), 'the log still has the old title')
  report(c, '02.1')
})

test('02.2 a card added from the command line appears in the open page without a reload', async () => {
  const c = new Checks()
  const p = project()
  mustRun(p, ['add', 'a', '--title', 'Use an append-only log'])
  const s = await serve(p.dir)
  const { page } = await open(s.port)
  const sub = page.getByRole('region', { name: 'sub-cards' })
  c.ok(await shows(page, () => sub.getByRole('link', { name: 'Use an append-only log' }).isVisible()), 'the page shows card a in the tree')
  await page.evaluate(() => Object.assign(window, { __noReload: true }))
  mustRun(p, ['add', 'c', '--title', 'Fold is pure'])
  mustRun(p, ['link', 'c', 'a', '--type', 'refines'])
  const under = await shows(page, async () => {
    const item = page.locator('li', { has: page.getByRole('link', { name: 'Use an append-only log', exact: true }) })
    return (await item.getByText('Fold is pure').count()) > 0
  })
  c.ok(under, 'the open page shows "Fold is pure" under "Use an append-only log"')
  const anywhere = await page.getByText('Fold is pure').count()
  c.note(`"Fold is pure" appears ${anywhere} time(s) on the open root page; the root page lists only top-level cards`)
  c.note(`root page text: ${(await page.locator('main').innerText()).replace(/\n/g, ' | ')}`)
  c.ok(await page.evaluate(() => (window as any).__noReload === true), 'the page did not reload')
  // A second look: the page of card a, opened by its link (a hash change, not a reload).
  await page.getByRole('link', { name: 'Use an append-only log', exact: true }).click()
  const onA = await shows(page, () => page.getByRole('region', { name: 'sub-cards' }).getByRole('link', { name: 'Fold is pure' }).isVisible())
  c.note(`after the user opens card a: its sub-cards show "Fold is pure": ${onA}`)
  report(c, '02.2')
}, 60_000)

test('02.3 a status change from the command line shows in the browser and in the command line', async () => {
  const c = new Checks()
  const p = project()
  mustRun(p, ['add', 'a', '--title', 'Use an append-only log', '--who', 'me'])
  mustRun(p, ['edit', 'a', '--no-basis', 'a root of the map'])
  mustRun(p, ['kill', 'a', 'revisit when the log format changes'])
  const s = await serve(p.dir)
  const { page } = await open(s.port)
  const row = page.getByRole('region', { name: 'sub-cards' }).locator('li', { has: page.getByRole('link', { name: 'Use an append-only log' }) })
  c.ok(await shows(page, async () => (await row.locator('.status').textContent()) === 'open'), 'the page shows a as open first')
  await page.evaluate(() => Object.assign(window, { __noReload: true }))
  const before = logEvents(p.dir)
  const r = p.run(['status', 'a', 'decided'])
  c.ok(r.code === 0, `status a decided exits 0: ${r.stdout.trim()} ${r.stderr.trim()}`)
  c.ok(await shows(page, async () => (await row.locator('.status').textContent()) === 'decided'), 'the page shows a as decided')
  c.ok(await page.evaluate(() => (window as any).__noReload === true), 'without a reload')
  c.ok(showCard(p, 'a')?.card.status === 'decided', 'show a prints status decided')
  const after = logEvents(p.dir)
  const added = after.slice(before.length)
  c.ok(added.length === 1 && added[0].type === 'decided' && added[0].id === 'a', `one status event for a: ${JSON.stringify(added)}`)
  c.ok(added[0]?.seq > Math.max(...before.map((e) => e.seq)), 'it comes after all earlier events')
  report(c, '02.3')
}, 60_000)

test('02.4 a card id in the location hash opens that card, and a reload keeps it', async () => {
  const c = new Checks()
  const p = project()
  mustRun(p, ['add', 'a', '--title', 'Use an append-only log'])
  mustRun(p, ['add', 'b', '--title', 'Cards fold from it', '--parent', 'a'])
  const s = await serve(p.dir)
  const { page } = await open(s.port, '#b')
  const h1 = page.getByRole('heading', { level: 1 })
  c.ok(await shows(page, async () => (await h1.textContent()) === 'Cards fold from it'), 'the page shows b as the open card')
  await page.reload()
  c.ok(await shows(page, async () => (await h1.textContent()) === 'Cards fold from it'), 'after a reload the page still shows b')
  c.ok(page.url().endsWith('#b'), `the url keeps #b: ${page.url()}`)
  report(c, '02.4')
}, 60_000)

test('02.5 a page control changes a card only by appending an event', async () => {
  const c = new Checks()
  const p = project()
  mustRun(p, ['add', 'a', '--title', 'Use an append-only log'])
  mustRun(p, ['add', 'b', '--title', 'Cards fold from it', '--parent', 'a'])
  const saved = logText(p.dir)
  const s = await serve(p.dir)
  const { page } = await open(s.port, '#b')
  await shows(page, async () => (await page.getByRole('heading', { level: 1 }).textContent()) === 'Cards fold from it')
  const controls = await page.locator('input, textarea, select, button, form, [contenteditable], [role=button], [role=checkbox], [role=menuitem]').count()
  c.ok(controls > 0, `the page of b has a control that changes the card (found ${controls} controls; links only read)`)
  c.note(`links on the page: ${(await page.getByRole('link').allInnerTexts()).join(', ')}`)
  c.ok(logText(p.dir) === saved, 'the log is unchanged (no control was used)')
  report(c, '02.5')
}, 60_000)
